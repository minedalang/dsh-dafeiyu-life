/**
 * Agent-scoped Life continuity handoff. The canonical Episode/relationship/
 * platform ledgers remain the only sources of facts. Handoffs are read-only,
 * deliberately omit contact identifiers and message text, and never grant a
 * tool permission or create a fresh action from a stale receipt.
 */
const AGENTS=new Set(['video','dm','comment','owner-dm','todo','social','reflection'])
const UID=/^[1-9]\d{0,18}$/
const ACTION=/^[a-z][a-z0-9_-]{1,45}$/
const BV=/^BV[0-9A-Za-z]{10}$/
const clean=(x,n=140)=>String(x??'').replace(/[\u0000-\u001f\u007f]/g,' ').trim().slice(0,n)
const channels={video:new Set(['video-agent','planner']),dm:new Set(['dm']),comment:new Set(['comment']), 'owner-dm':new Set(['owner-dm']),todo:new Set(['owner-todo','todo-followup']),social:new Set(['social-agent']),reflection:new Set(['reflection-public'])}
// Only the original, authenticated source's Episode can be handed back to an
// individual conversation/task. A caller never gets to turn an arbitrary
// sourceRef into a cross-person memory search.
const sourcePatterns={dm:/^dm-conversation:[1-9]\d{0,18}$/,comment:/^comment-thread:BV[0-9A-Za-z]{10}:[1-9]\d{0,18}$/, 'owner-dm':/^owner-dm-conversation:[1-9]\d{0,18}$/,todo:/^todo:[0-9a-zA-Z_-]{1,100}$/,social:/^social-receipt:[^\u0000-\u001f\u007f]{1,160}$/,reflection:/^reflection:reflection-run:[^\u0000-\u001f\u007f]{1,130}$/}
/** Current account and original source are checked by the supplied Episode ledger. */
export function lifeSubagentHandoff({agent,episodes,sourceRef='',linkedPublicBvid='',limit=3}={}){
  if(!AGENTS.has(agent)||!episodes)return {agent:'unknown',recent:[],source:null}
  const safeView=row=>{
    if(!row||typeof row!=='object')return null
    return {status:row.status==='review'?'review':row.status==='paused'?'paused':row.status==='completed'?'completed':'active',
      steps:Math.max(0,Math.min(5,Number(row.steps)||0)),
      history:(Array.isArray(row.history)?row.history:[]).slice(-5).filter(x=>x&&ACTION.test(String(x.action||''))&&channels[agent].has(x.channel))
        .map(x=>({action:x.action,outcome:clean(x.outcome,24),channel:x.channel})),
      nextAt:Number.isSafeInteger(row.nextAt)?row.nextAt:0}
  }
  try{
    const allowedSource=typeof sourceRef==='string'&&sourcePatterns[agent]?.test(sourceRef)
    const source=allowedSource&&typeof episodes.sourceState==='function'?safeView(episodes.sourceState(sourceRef)):null
    // Never show another DM/comment subject's activity to this person's
    // model. Only video can see its own public, anonymous global episodes.
    const recent=['video','todo','social','reflection'].includes(agent)&&typeof episodes.list==='function'
      ?episodes.list({limit:20}).filter(x=>
          agent==='video'?['video','exploration'].includes(x.kind):
          agent==='todo'?x.kind==='todo':
          agent==='reflection'?x.kind==='reflection':x.kind==='social')
        .map(safeView).filter(x=>x?.history?.length).slice(0,Math.max(1,Math.min(5,limit)))
      :[]
    // This is a verified PUBLIC video-action bridge, not a user search or a
    // permission. Caller must supply a BV from the current trusted platform
    // event; never accept a BV generated by the model. No private DM/reflection
    // events are projected into this anchor, even for the same video.
    const publicVideo=['video','comment'].includes(agent)&&BV.test(String(linkedPublicBvid||''))&&
      typeof episodes.publicVideoState==='function'
      ?episodes.publicVideoState(linkedPublicBvid):null
    const bridge=publicVideo?{
      status:['active','paused','completed','review'].includes(publicVideo.status)?publicVideo.status:'review',
      history:(Array.isArray(publicVideo.history)?publicVideo.history:[]).slice(-5)
        .filter(x=>x&&['video-agent','comment'].includes(x.channel)&&ACTION.test(String(x.action||''))&&
          ['verified','completed','considered'].includes(x.outcome))
        .map(x=>({action:x.action,channel:x.channel,outcome:x.outcome}))}:null
    return {agent,source:source?.history.length?source:null,recent,
      publicVideo:bridge?.history.length?bridge:null}
  }catch{return {agent,source:null,recent:[]}}
}
/** This is a *candidate*, not follow permission. All evidence comes from the
 * same already authenticated inbox sender. Age and turn count prevent an
 * isolated request/prompt injection from creating a new social capability. */
export function dmContactFollowCandidates({enabled=false,uid='',role='',history=[],optedOut=false,now=Date.now()}={}){
  if(enabled!==true||!UID.test(String(uid))||!Number.isSafeInteger(Number(uid))||String(Number(uid))!==String(uid)||role!=='friend'||optedOut||!Array.isArray(history))return []
  const rows=history.filter(x=>x&&['user','assistant'].includes(x.role)&&Number.isSafeInteger(Number(x.at))&&
    Number(x.at)>0&&now-Number(x.at)<=90*86400_000&&now>=Number(x.at))
  const inbound=rows.filter(x=>x.role==='user'),outbound=rows.filter(x=>x.role==='assistant')
  if(inbound.length<3||outbound.length<3||rows.length<6)return []
  const first=Math.min(...rows.map(x=>Number(x.at)))
  if(now-first<86400_000)return []
  return [{id:'follow_dm_contact',action:'follow_dm_contact',label:'自主考虑关注这位长期交流的私信联系人（需独立授权及平台复核）',risk:'outbound-write'}]
}
export function validateSubagentNextAction(proposed,candidates=[]){
  if(!proposed||typeof proposed!=='object'||Array.isArray(proposed))return null
  const id=clean(proposed.action,50),reason=clean(proposed.reason,160)
  if(Object.keys(proposed).some(key=>!['action','reason'].includes(key))||!ACTION.test(id)||!candidates.some(c=>c.action===id)||reason.length<8)return null
  return {action:id,reason}
}

/** A runtime menu for each specialized agent. This is intentionally a
 * projection of capabilities actually passed by its trusted host. No default
 * write permission, arbitrary UID/BV, or generic network tool is created.
 * Models may choose to finish or pause at any step. */
const READ_CONTEXT=new Set(['todo','recommendation','memory','portrait','meme','video','history','public_person'])
const OWNER_READ=new Set(['memory_search','memory_detail','public_comments','recent_actions',
  'search','watch','inspect_my_space','inspect_creator_videos','check_notifications'])
const OWNER_WRITE=new Set(['like','collect','follow','unfollow','comment_draft',
  'comment_publish','comment_publish_draft','dynamic_draft','dynamic_publish','message'])
export function subagentActionMenu({agent,readKinds=[],tools=[],nextActions=[],episode=null}={}){
  if(!AGENTS.has(agent))return []
  const menu=[]
  const add=(action,risk='read',description='')=>{
    if(ACTION.test(action)&&!menu.some(x=>x.action===action))menu.push({action,risk,description:clean(description,100)})
  }
  // Advertise only actions each host can actually accept. A conceptual
  // wish like 'pause' is not a callable tool and must not be presented as one.
  if(agent==='video')add('stop','none','不再调用工具，结束本轮视频探索')
  if(agent==='social'||agent==='todo')add('skip','none','本轮不采取新行动')
  if(['dm','comment','owner-dm'].includes(agent)){
    add('reply','outbound-existing','自然回复；发送由原社交事务独立审批')
    if(agent!=='owner-dm')add('skip','none','这次选择沉默')
  }
  if(['dm','comment'].includes(agent)){
    add('defer','existing-continuation','已有 P6 预约机制启用时延期考虑')
    add('close','none','结束当前话题')
    for(const kind of readKinds)if(READ_CONTEXT.has(kind))add('read_'+kind,'read','按当前账号／会话权限读取'+kind)
  }
  if(agent==='owner-dm'){
    for(const action of tools)if(OWNER_READ.has(action))add(action,'read','主人私信现有只读工具')
    for(const action of tools)if(OWNER_WRITE.has(action))add(action,'outbound-existing','仅本条主人明确授权的新写操作')
  }
  if(agent==='video')for(const tool of tools)if(typeof tool==='string'&&/^bili_[a-z_]{3,45}$/.test(tool))
    add(tool,/reply|like|collect|follow|publish|dynamic/.test(tool)?'outbound-existing':'read','视频 Agent 现有 MCP 工具（执行器再复核）')
  if(agent==='todo')for(const action of tools)if(['execute_read','defer','dismiss','review_result'].includes(action))
    add(action,action==='execute_read'?'read':'existing-task','原待办状态和权限约束')
  if(agent==='social')for(const action of tools)if(['consider_social','review_friend','reach_out_friend',
    'inspect_public_person','review_public','defer','dismiss'].includes(action))
    add(action,action==='reach_out_friend'?'outbound-existing':'read','Life 当轮核验候选')
  if(agent==='reflection')add('reflect','read-only-reasoning','只使用仍可访问的同域证据形成认识')
  for(const candidate of nextActions)if(candidate&&candidate.action==='follow_dm_contact'&&agent==='dm')
    add('follow_dm_contact','outbound-write-proposal','仅提出长期联系人关注意愿；不直接执行')
  return menu.slice(0,40)
}
/** Validate a model's requested read against the same, live menu. */
export function acceptedSubagentReadKinds(requested,menu){
  if(!Array.isArray(requested)||!Array.isArray(menu)||requested.length>4)return null
  const offered=new Set(menu.filter(x=>x.risk==='read').map(x=>x.action))
  const result=[]
  for(const kind of requested){
    if(!READ_CONTEXT.has(kind)||!offered.has('read_'+kind))return null
    if(!result.includes(kind))result.push(kind)
  }
  return result
}

