export function classifyRuntimeLine(line,{source=''}={}){
 const text=String(line),time=text.match(TIMESTAMP)?.[1]||null,head=text.split('\n',1)[0].replace(TIMESTAMP,'').trim()
 const declared=head.match(DECLARED)?.[1]?.toLowerCase(),eventHead=(declared?head.replace(DECLARED,'').trim():head).replace(/^(?:⚠️|🔒)\s*/u,'')
 const install=/^(?:install|asr-install)\.log$/.test(source),stats=eventHead.startsWith('本轮视频工具漏斗：'),counts=stats?eventCounts(eventHead):[]
 const retry=/^本地语义运行时：[^，]{0,80}下载源失败，尝试下一个来源：/u.test(eventHead)
 const setupBlocked=eventHead.startsWith('评论互动错误：')&&/快速设置还需在大肥鱼管理中心确认完成/u.test(eventHead)
 const exit=eventHead.match(/^(?:刷B站结束|装依赖结束|装转写依赖结束)[^\n]*?(?:code|exit)=(\d+)(?:\/(\d+))?/u)
 const exitFailed=exit&&[exit[1],exit[2]].some(n=>n!==undefined&&Number(n)!==0)
 const installFailure=install&&text.split('\n').some(l=>INSTALL_FAILURE.test(l.replace(TIMESTAMP,'')))
 const knownFailure=FAILURE_HEADER.test(eventHead)||/^(?:failed|fatal|Traceback)(?:\s|:)/i.test(eventHead)||Boolean(eventHead.match(EXCEPTION)&&/^\w+Error:/.test(eventHead))||/^[^，,：:。；;\n]{1,70}(?:失败|错误|异常|超时)(?=[:：（(]|$)/u.test(eventHead)
 let level='info'
 if(declared)level=['error','fatal'].includes(declared)?'error':declared.startsWith('warn')?'warning':'info'
 else if(stats)level=counts.some(x=>x.label==='工具错误'&&x.value>0)?'warning':'info'
 else if(retry||setupBlocked)level='warning'
 else if(exit)level=exitFailed?'error':'info'
 else if(POSITIVE_PREFIX.test(eventHead))level='info'
 else if(/^(?:评论互动警告|警告[:：]|退避[:：]|限流[:：]|dsh: warning:)/iu.test(eventHead))level='warning'
 else if(knownFailure||installFailure||CODE.test(eventHead))level='error'
 // Continuations belong to their event, but cannot upgrade an otherwise successful
 // header: they may contain video titles, private summaries or model reasoning.
 const diagnostic=level==='info'?'':install||knownFailure||declared?text:eventHead
 const reason=diagnostic.match(CODE)?.[0]?.trim().toUpperCase()||null
 const exception=diagnostic.match(EXCEPTION)?.[0]||null
 const fetchFailed=/\bfetch failed\b/i.test(diagnostic)
 const category=stats?'video':setupBlocked?'auth':retry||fetchFailed?'network':categories.find(([,pattern])=>pattern.test(eventHead+' '+(reason||'')))?.[0]||'other'
 let label=EVENT_LABELS.find(([prefix])=>eventHead.startsWith(prefix)||eventHead.startsWith('⚠️ '+prefix)||eventHead.startsWith('🔒 '+prefix))?.[1]
 if(retry)label='本地语义运行时下载源失败，尝试备用来源'
 else if(setupBlocked)label='首次配置尚未完成，评论检测暂缓'
 else if(eventHead.startsWith('本地语义模型安装失败'))label='本地语义模型安装失败'
 else if(eventHead.startsWith('刷B站开跑失败'))label='视频探索启动失败'
 else if(eventHead.startsWith('评论复核失败'))label='评论复核失败'
 else if(eventHead.startsWith('总开关文件同步失败')||eventHead.startsWith('总开关状态文件同步失败'))label='运行开关状态同步失败'
 else if(eventHead.startsWith('单条笔记：新写了'))label='视频笔记写入完成'
 else if(eventHead.startsWith('本轮原创主评论诊断：'))label='本轮原创评论诊断'
 else if(eventHead.startsWith('装依赖结束'))label='运行依赖安装结束'
 else if(eventHead.startsWith('本地语义回忆索引同步完成'))label='本地语义索引同步完成'
 if(install&&!time)label=level==='error'?'依赖安装输出中检测到异常':'依赖安装输出'
 const detail=setupBlocked?'需要完成首次配置后再启动业务。':reason?ERROR_DETAILS[reason]||reason:fetchFailed?(retry||eventHead.startsWith('本地语义模型安装失败')?'下载请求失败':'网络请求失败')+'（fetch failed）；日志未提供更具体的网络原因。':exception?`异常类型：${exception}`:exit?`退出码：${exit[1]}${exit[2]===undefined?'':' / '+exit[2]}`:null
 return {time,level,category,reason,message:label||(detail&&!exit?detail:level==='error'?'未识别的异常事件':level==='warning'?'未识别的警告事件':'未分类运行记录'),detail:label?detail:null,exception,...(counts.length?{counts}:{}),...(retry?{retrying:true}:{})}
}
export function parseRuntimeEvents(text,{source='',truncated=false}={}){
 const events=[];let lines=[],lineNo=0,startLine=1,first=true
 const emit=()=>{if(!lines.length)return;const row=classifyRuntimeLine(lines.join('\n'),{source});events.push({...row,source,lineStart:startLine,lineCount:lines.length});lines=[]}
 for(const line of String(text).split(/\r?\n/)){
  lineNo++;if(first&&truncated){first=false;continue}first=false
  if(!line.trim())continue
  if(TIMESTAMP.test(line)){emit();startLine=lineNo}
  else if(!lines.length)startLine=lineNo
  lines.push(line)
 }
 emit();return events
}
export function readRuntimeLogs(dir,{errorsOnly=false,exportAll=false}={}){
 const coverage=[],rows=[];let errors=0,matched=0
 for(const source of SOURCES){
  let fd
  try{
   const path=join(dir,source),before=lstatSync(path)
   if(!before.isFile()||before.isSymbolicLink())throw Error('not-regular-file')
   fd=openSync(path,constants.O_RDONLY|(constants.O_NOFOLLOW||0));const st=fstatSync(fd)
   if(!st.isFile()||st.dev!==before.dev||st.ino!==before.ino)throw Error('file-changed')
   const start=Math.max(0,st.size-MAX_BYTES),buf=Buffer.alloc(st.size-start)
   let n=0;while(n<buf.length){const got=readSync(fd,buf,n,buf.length-n,start+n);if(!got)break;n+=got}
   let count=0,errorCount=0
   for(const row of parseRuntimeEvents(buf.subarray(0,n).toString('utf8'),{source,truncated:start>0})){
    count++;if(row.level==='error'){errors++;errorCount++}
    if(errorsOnly&&row.level!=='error')continue
    matched++;rows.push({...row,record:count,windowStartByte:start});if(rows.length>MAX_ROWS*2)rows.splice(0,MAX_ROWS)
   }
   coverage.push({source,status:'read',bytes:st.size,readBytes:n,windowStartByte:start,truncated:start>0||n!==buf.length,records:count,errors:errorCount})
  }catch(e){coverage.push({source,status:e?.code==='ENOENT'?'absent':'unavailable'})}finally{if(fd!==undefined)closeSync(fd)}
 }
 const max=exportAll?MAX_ROWS:300
 return {ok:true,format:'runtime-log-summary/v2',capturedAt:new Date().toISOString(),coverage,errors,matched,omitted:Math.max(0,matched-max),rows:rows.sort((a,b)=>(Date.parse(b.time)||0)-(Date.parse(a.time)||0)||SOURCES.indexOf(b.source)-SOURCES.indexOf(a.source)||b.record-a.record).slice(0,max),rawIncluded:false}
}
